/** 文に入る値。JSON にそのまま書ける値だけを持つ。 */
export type ApiErrorDetailValue =
  | string
  | number
  | boolean
  | null
  | readonly ApiErrorDetailValue[]
  | { readonly [field: string]: ApiErrorDetailValue };

/** error・code の横に置く項目。同じ名前の項目があっても、本文の error と code が優先する。 */
export type ApiErrorDetails = { readonly [field: string]: ApiErrorDetailValue };

/** エラー応答の本文。横の項目は code ごとに決まる。 */
export interface ApiErrorBody {
  error: string;
  code: ApiErrorCode;
  readonly [field: string]: unknown;
}
